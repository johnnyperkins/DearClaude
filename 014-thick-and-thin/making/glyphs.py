# The hand. Every glyph as the strokes a broad pen makes, in the order it makes them.
# Coordinates: x is the nib's centre; y is where the ink's edge lands at the top and bottom (see nib.zone).
# A stroke is a path string, or (path, {'angle': a, 'to': b}) to hold the pen at another angle, or turn it as it goes.
# sides: spacing for the left and right. 'S' a straight stem, 'R' a round, both measured from the glyph's
# middle band; a number is units from the glyph's outermost ink.
import re
import unicodedata

GLYPHS = {}


def g(name, char, strokes, sides=('S', 'S'), frame='lc', **kw):
    GLYPHS[name] = dict(char=char, strokes=strokes, sides=sides, frame=frame, **kw)


def G(name, char, strokes, sides=('S', 'S'), **kw):
    g(name, char, strokes, sides, 'uc', **kw)


def hook(x, top):
    """Entry serif: a thin lead-in up and to the right, then down into a stem at x."""
    return f"M {x-36} {top-44} C {x-24} {top-26} {x-10} {top} {x+2} {top} C {x+3} {top-22} {x} {top-50} {x} {top-82}"


def foot(x):
    """The stem turns right as the pen leaves the paper."""
    return f" L {x} 46 C {x} 16 {x+12} 0 {x+44} 6"


def arch(x0, x1, top=478, spring=280):
    """An arch that branches out of a stem at x0 and comes down as a stem at x1."""
    w = x1 - x0
    return (f"M {x0+2} {spring} C {x0+w*0.08} {spring+100} {x0+w*0.33} {top} {x0+w*0.57} {top} "
            f"C {x0+w*0.86} {top} {x1} {top-62} {x1} {top-150}")


def dot(x, bottom, h=52):
    """A short stroke straight across the nib: the pen's own footprint, a lozenge."""
    return f"M {x-h*0.3:.0f} {bottom+h} L {x+h*0.3:.0f} {bottom}"


def mirror(d, w):
    """The same path reflected left to right inside a width w."""
    out, k = [], 0
    for t in re.findall(r'[MLCQ]|-?\d+(?:\.\d+)?', d):
        if t in 'MLCQ':
            out.append(t); k = 0
        else:
            out.append(str(round(w - float(t), 2)) if k % 2 == 0 else t); k += 1
    return ' '.join(out)


def turn(d, cx, cy):
    """The same path turned upside down about (cx, cy)."""
    out, k = [], 0
    for t in re.findall(r'[MLCQ]|-?\d+(?:\.\d+)?', d):
        if t in 'MLCQ':
            out.append(t); k = 0
        else:
            out.append(str(round(2 * (cx if k % 2 == 0 else cy) - float(t), 2))); k += 1
    return ' '.join(out)


